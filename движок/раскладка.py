def длительность(src):
    r = subprocess.run(["ffprobe", "-v", "error", "-show_entries",
                        "format=duration", "-of", "csv=p=0", str(src)],
                       capture_output=True, text=True, errors="replace")
    try:
        return float(r.stdout.strip())
    except ValueError:
        return 0.0


def снять_кадры(src, n, куда):
    """Кадры в полном разрешении, равномерно по стриму, без первых и последних 5 %."""
    куда.mkdir(parents=True, exist_ok=True)
    дл = длительность(src)
    if дл <= 0:
        print("  ffprobe не прочитал длительность. Файл ещё качается?")
        return []
    метки = [дл * (0.05 + 0.90 * i / max(n - 1, 1)) for i in range(n)]
    пути = []
    for i, t in enumerate(метки, 1):
        п = куда / ("кадр-%02d.png" % i)
        subprocess.run(["ffmpeg", "-y", "-v", "error", "-ss", "%.2f" % t,
                        "-i", str(src), "-frames:v", "1", str(п)],
                       capture_output=True)
        if п.exists():
            пути.append((t, п))
    return пути


