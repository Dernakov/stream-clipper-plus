def _размыть(м, радиус):
    """Коробчатое размытие через интегральную картинку — нужно только для поиска пятна."""
    H, W = м.shape
    инт = np.pad(м.cumsum(0).cumsum(1), ((1, 0), (1, 0)))
    y0 = np.clip(np.arange(H) - радиус, 0, H)
    y1 = np.clip(np.arange(H) + радиус + 1, 0, H)
    x0 = np.clip(np.arange(W) - радиус, 0, W)
    x1 = np.clip(np.arange(W) + радиус + 1, 0, W)
    сумма = (инт[np.ix_(y1, x1)] - инт[np.ix_(y0, x1)]
             - инт[np.ix_(y1, x0)] + инт[np.ix_(y0, x0)])
    площадь = np.outer(y1 - y0, x1 - x0).astype(np.float32)
    return сумма / np.maximum(площадь, 1)


def найти_лицо(кадры, окно):
    """
    Где внутри окна вебки сидит лицо.

    Главный признак — ДВИЖЕНИЕ: в кадре вебки шевелится ровно человек,
    комната за ним стоит. Кожа идёт вторым, поправочным множителем: одной
    кожи мало (ловит стену, светильник, песок в игре), одного движения
    тоже мало (рука двигается сильнее лица). На этом у автора автоподбор
    кадра ломался четыре раза подряд, пока не стало «кожа И движение».

    Ищем только в верхних 3/4 окна: лицо сидит там, а снизу торс и руки.
    """
    if len(кадры) < 2 or not окно or окно.get("w", 0) < 40:
        return None
    x, y, w, h = окно["x"], окно["y"], окно["w"], окно["h"]
    куски = [к[y:y + h, x:x + w] for к in кадры]
    стопка = np.stack([к.mean(axis=2) for к in куски])
    движение = стопка.std(axis=0)

    средний = np.mean(куски, axis=0)
    R, G, B = средний[:, :, 0], средний[:, :, 1], средний[:, :, 2]
    кожа = ((R > 60) & (R > G + 10) & (G > B) & ((R - B) > 14)
            & (R < 250)).astype(np.float32)

    оценка = движение * (0.35 + кожа)
    верх = int(h * 0.75)
    оценка[верх:, :] *= 0.25

    сглажено = _размыть(оценка, max(6, w // 10))
    if float(сглажено.max()) < 0.8:
        return None
    сy, сx = np.unravel_index(int(np.argmax(сглажено)), сглажено.shape)
    return int(x + сx), int(y + сy)


def _пики(профиль, сколько=20, расстояние=10):
    """Самые выраженные вершины профиля, без соседей-дублей."""
    п = np.array(профиль, dtype=np.float64)
    выбраны = []
    for _ in range(сколько):
        i = int(np.argmax(п))
        if п[i] <= 0:
            break
        выбраны.append(i)
        п[max(0, i - расстояние):i + расстояние + 1] = -1
    return выбраны


def _самый_длинный_отрезок(карта, ось, окно):
    """
    Насколько сильная ПРЯМАЯ грань есть в каждой строке (или столбце).

    Считать сумму по всей ширине кадра нельзя: грань вебки занимает
    четверть строки, и в сумме её забивают строки, пересекающие кадр
    целиком — именно поэтому первая версия не видела настоящее окно.
    Поэтому берём скользящее среднее длиной с типичную грань и её максимум.
    """
    м = карта if ось == 0 else карта.T          # строки в первой оси
    инт = np.pad(м.cumsum(axis=1), ((0, 0), (1, 0)))
    окно = int(min(окно, м.shape[1] - 1))
    скольз = (инт[:, окно:] - инт[:, :-окно]) / окно
    return скольз.max(axis=1)


def найти_окно(средний, кадры, угол, явный_угол=False):
    """
    Границы окна вебки.

    Как НЕ надо. Первая версия искала самую резкую горизонтальную и самую
    резкую вертикальную границу по отдельности — и цеплялась за панели
    интерфейса игры. Вторая искала лицо по коже и рамку вокруг него — и на
    PUBG уехала в песчаную стену: песок по цвету ровно кожа, а камера
    панорамирует, так что «кожа И движение» совпало идеально.

    Как надо. Вебка — это ПРЯМОУГОЛЬНИК: четыре грани, и они согласованы
    между собой. Поэтому перебираем прямоугольники, собранные из сильных
    строк и столбцов, и требуем, чтобы поддержаны были ВСЕ ЧЕТЫРЕ грани
    (берём минимум из четырёх, а не сумму). Отдельная панель интерфейса
    столько граней не наберёт.

    Грани ищем по СРЕДНЕЙ картинке: на ней движущееся смазано, а
    неподвижная рамка остаётся резкой. Плюс требуем, чтобы внутри окна
    картинка ЖИЛА — это отсекает статичные таблицы и миникарты.
    """
    H, W = средний.shape[:2]
    серый = средний.mean(axis=2)
    Hor = np.abs(np.diff(серый, axis=0))          # (H-1, W)
    Ver = np.abs(np.diff(серый, axis=1))          # (H, W-1)
    Hcum = np.pad(Hor.cumsum(axis=1), ((0, 0), (1, 0)))
    Vcum = np.pad(Ver.cumsum(axis=0), ((1, 0), (0, 0)))

    строки = sorted(set(_пики(_самый_длинный_отрезок(Hor, 0, 240), 26)
                        + [0, H - 2]))
    столбцы = sorted(set(_пики(_самый_длинный_отрезок(Ver, 1, 140), 26)
                         + [0, W - 2]))

    шевеление = np.std(np.stack([к.mean(axis=2) for к in кадры]), axis=0)
    Scum = np.pad(шевеление.cumsum(0).cumsum(1), ((1, 0), (1, 0)))

    def жизнь(x0, y0, x1, y1):
        s = (Scum[y1, x1] - Scum[y0, x1] - Scum[y1, x0] + Scum[y0, x0])
        return s / max((x1 - x0) * (y1 - y0), 1)

    def гор_среднее(y, x0, x1):
        y = int(np.clip(y, 0, H - 2))
        return (Hcum[y, x1] - Hcum[y, x0]) / max(x1 - x0, 1)

    def вер_среднее(x, y0, y1):
        x = int(np.clip(x, 0, W - 2))
        return (Vcum[y1, x] - Vcum[y0, x]) / max(y1 - y0, 1)

    def гор_контраст(y, x0, x1):
        """Грань против собственного фона: текст даёт грани везде, рамка — только на линии."""
        фон = np.mean([гор_среднее(y + d, x0, x1) for d in (-7, -5, 5, 7)])
        return гор_среднее(y, x0, x1) / (фон + 1e-6)

    def вер_контраст(x, y0, y1):
        фон = np.mean([вер_среднее(x + d, y0, y1) for d in (-7, -5, 5, 7)])
        return вер_среднее(x, y0, y1) / (фон + 1e-6)

    пары_строк = [(a, b) for a in строки for b in строки
                  if 100 <= b - a <= H * 0.6]
    пары_столбцов = [(a, b) for a in столбцы for b in столбцы
                     if 150 <= b - a <= W * 0.6]

    площадь_кадра = float(W * H)
    лучший, лучшая_оценка = None, 0.0

    for y0, y1 in пары_строк:
        h = y1 - y0
        for x0, x1 in пары_столбцов:
            w = x1 - x0
            доля = w * h / площадь_кадра
            if доля < 0.012 or доля > 0.28:
                continue
            проп = w / h
            if проп < 1.05 or проп > 2.3:      # вебка landscape: 4:3 или 16:9
                continue
            # Грань, совпавшая с краем кадра, физически не видна.
            # Не штрафуем за неё: подставим медиану видимых.
            видно = [y0 > 2, y1 < H - 4, x0 > 2, x1 < W - 4]
            if sum(видно) < 2:
                continue
            грани = [
                гор_контраст(y0, x0, x1) if видно[0] else None,
                гор_контраст(y1, x0, x1) if видно[1] else None,
                вер_контраст(x0, y0, y1) if видно[2] else None,
                вер_контраст(x1, y0, y1) if видно[3] else None,
            ]
            реальные = [г for г in грани if г is not None]
            подстановка = float(np.median(реальные))
            оценка = float(min(г if г is not None else подстановка for г in грани))
            if оценка < 1.15:
                continue
            if жизнь(x0, y0, x1, y1) < 1.5:    # статичная панель, не живое видео
                continue
            в_углу = ((x0 <= 4 or x1 >= W - 6) and (y0 <= 4 or y1 >= H - 6))
            if в_углу:
                оценка *= 1.25
            if явный_угол:
                свой = (("лево" in угол and x0 <= 4) or
                        ("право" in угол and x1 >= W - 6)) and \
                       (("низ" in угол and y1 >= H - 6) or
                        ("верх" in угол and y0 <= 4))
                оценка *= 1.35 if свой else 0.75
            if оценка > лучшая_оценка:
                лучшая_оценка = оценка
                лучший = (x0, y0, x1, y1)

    if лучший is None:
        return dict(x=0, y=0, w=0, h=0), 0.0, None

    x0, y0, x1, y1 = лучший
    окно = dict(x=int(x0 + 1), y=int(y0 + 1), w=int(x1 - x0), h=int(y1 - y0))
    # Уверенность — во сколько раз слабейшая грань контрастнее своего фона.
    # 1.0 значит «грани нет вовсе», 2 и выше — честная рамка.
    return окно, float(лучшая_оценка), найти_лицо(кадры, окно)


def постоянная_графика(кадры, окно):
    """
    Подсказка про вотермарк и баннеры: где картинка НЕ меняется весь стрим,
    но при этом контрастная. Это не приговор, а повод посмотреть глазами.
    """
    if len(кадры) < 3:
        return []
    стопка = np.stack([к.mean(axis=2) for к in кадры])
    разброс = стопка.std(axis=0)
    средний = стопка.mean(axis=0)
    контраст = np.abs(np.diff(средний, axis=1, prepend=средний[:, :1]))
    подозрение = (разброс < 4.0) & (контраст > 12.0)
    H, W = подозрение.shape
    # гасим саму вебку — там своя рамка
    x, y, w, h = окно["x"], окно["y"], окно["w"], окно["h"]
    подозрение[max(0, y - 4):y + h + 4, max(0, x - 4):x + w + 4] = False
    по_строкам = подозрение.sum(axis=1)
    порог = max(W * 0.02, 12)
    зоны, тек = [], None
    for yy, знач in enumerate(по_строкам):
        if знач > порог and тек is None:
            тек = yy
        elif знач <= порог and тек is not None:
            if yy - тек >= 8:
                зоны.append((тек, yy))
            тек = None
    if тек is not None and H - тек >= 8:
        зоны.append((тек, H))
    return зоны


