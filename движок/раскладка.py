def шрифт(размер):
    try:
        return ImageFont.truetype(str(ШРИФТ), размер)
    except Exception:
        return ImageFont.load_default()


def нарисовать_сетку(кадр_путь, куда, шаг=100):
    им = Image.open(кадр_путь).convert("RGB")
    d = ImageDraw.Draw(им)
    W, H = им.size
    ф = шрифт(22)
    for x in range(0, W, шаг):
        крупно = x % (шаг * 5) == 0
        d.line([(x, 0), (x, H)], fill=(0, 255, 0) if крупно else (0, 120, 0),
               width=2 if крупно else 1)
        if крупно:
            d.text((x + 4, 4), str(x), fill=(0, 255, 0), font=ф,
                   stroke_width=3, stroke_fill=(0, 0, 0))
    for y in range(0, H, шаг):
        крупно = y % (шаг * 5) == 0
        d.line([(0, y), (W, y)], fill=(0, 255, 0) if крупно else (0, 120, 0),
               width=2 if крупно else 1)
        if крупно:
            d.text((4, y + 4), str(y), fill=(0, 255, 0), font=ф,
                   stroke_width=3, stroke_fill=(0, 0, 0))
    им.save(куда)


def нарисовать_рамки(кадр_путь, окно, кропы, игра, куда):
    им = Image.open(кадр_путь).convert("RGB")
    d = ImageDraw.Draw(им)
    ф = шрифт(26)
    d.rectangle([окно["x"], окно["y"], окно["x"] + окно["w"], окно["y"] + окно["h"]],
                outline=(0, 255, 0), width=4)
    d.text((окно["x"] + 6, окно["y"] + 6), "ОКНО ВЕБКИ", fill=(0, 255, 0), font=ф,
           stroke_width=3, stroke_fill=(0, 0, 0))
    цвета = [(255, 60, 60), (60, 160, 255), (255, 220, 0), (255, 0, 255), (0, 255, 255)]
    for i, (имя, (w, h, x, y)) in enumerate(кропы.items()):
        c = цвета[i % len(цвета)]
        d.rectangle([x, y, x + w, y + h], outline=c, width=2)
        d.text((x + 4, y + h - 30), имя, fill=c, font=ф,
               stroke_width=3, stroke_fill=(0, 0, 0))
    for i, (имя, г) in enumerate(игра.items()):
        c = цвета[i % len(цвета)]
        d.rectangle([г["x"], г["y"], г["x"] + г["w"], г["y"] + г["h"]],
                    outline=c, width=3)
        d.text((г["x"] + 8, г["y"] + 8), "игра: " + имя, fill=c, font=ф,
               stroke_width=3, stroke_fill=(0, 0, 0))
    им.save(куда)


def нарисовать_кропы(кадр_путь, кропы, куда, высота=520):
    """Как будет выглядеть лицо в каждом стиле — рядом, в одном масштабе."""
    им = Image.open(кадр_путь).convert("RGB")
    панели = []
    for имя, (w, h, x, y) in кропы.items():
        кусок = им.crop((x, y, x + w, y + h))
        ш = max(1, int(кусок.width * высота / max(кусок.height, 1)))
        кусок = кусок.resize((ш, высота), Image.LANCZOS)
        полотно = Image.new("RGB", (кусок.width, высота + 44), (20, 20, 20))
        полотно.paste(кусок, (0, 44))
        d = ImageDraw.Draw(полотно)
        d.text((8, 8), "%s  %dx%d" % (имя, w, h), fill=(255, 255, 255), font=шрифт(24))
        панели.append(полотно)
    if not панели:
        return
    общая = Image.new("RGB", (sum(п.width + 10 for п in панели),
                              высота + 44), (20, 20, 20))
    x = 0
    for п in панели:
        общая.paste(п, (x, 0))
        x += п.width + 10
    общая.save(куда)


def контактный_лист(пути, куда, колонок=3, ширина=520):
    кадры = [Image.open(п).convert("RGB") for _, п in пути]
    if not кадры:
        return
    к = ширина / кадры[0].width
    выс = int(кадры[0].height * к)
    строк = (len(кадры) + колонок - 1) // колонок
    лист = Image.new("RGB", (ширина * колонок, (выс + 30) * строк), (15, 15, 15))
    d = ImageDraw.Draw(лист)
    ф = шрифт(22)
    for i, (им, (t, _)) in enumerate(zip(кадры, пути)):
        cx = (i % колонок) * ширина
        cy = (i // колонок) * (выс + 30)
        лист.paste(им.resize((ширина, выс), Image.LANCZOS), (cx, cy + 30))
        d.text((cx + 8, cy + 5), "%d:%02d:%02d" % (t // 3600, t % 3600 // 60, t % 60),
               fill=(255, 255, 255), font=ф)
    лист.save(куда)


