def кроп_под_блок(окно, блок, крупность, лицо, запас=2):
    """Наибольший прямоугольник нужной пропорции внутри окна, по центру лица."""
    ow, oh = окно["w"] - запас * 2, окно["h"] - запас * 2
    пропорция = блок[0] / блок[1]
    h = min(oh, ow / пропорция)
    w = h * пропорция
    h, w = h * крупность, w * крупность
    w, h = int(round(w)), int(round(h))
    # держим пропорцию ровно: перекос даже на пиксель даёт растяжку
    h = int(round(w / пропорция))
    цx = лицо[0] if лицо else окно["x"] + окно["w"] // 2
    цy = лицо[1] if лицо else окно["y"] + окно["h"] // 2
    x = int(round(цx - w / 2))
    y = int(round(цy - h / 2))
    x = max(окно["x"] + запас, min(x, окно["x"] + окно["w"] - запас - w))
    y = max(окно["y"] + запас, min(y, окно["y"] + окно["h"] - запас - h))
    return w, h, x, y


def кроп_игры(кадр_wh, окно, блок, верх, низ, лево, угол):
    """Кусок игры: мимо окна вебки, с запасами сверху и снизу."""
    W, H = кадр_wh
    пропорция = блок[0] / блок[1]
    if "лево" in угол:
        x0, x1 = окно["x"] + окно["w"] + лево, W
    else:
        x0, x1 = 0, окно["x"] - лево
    y0, y1 = верх, H - низ
    дост_w, дост_h = max(x1 - x0, 10), max(y1 - y0, 10)
    h = min(дост_h, дост_w / пропорция)
    w = h * пропорция
    if w > дост_w:
        w = дост_w
        h = w / пропорция
    w, h = int(round(w)), int(round(h))
    h = int(round(w / пропорция))
    x = int(x0 + (дост_w - w) / 2)
    y = int(y0 + (дост_h - h) / 2)
    return dict(w=w, h=h, x=max(0, x), y=max(0, y))


