def раскладка_в_словарь(блок):
    """Блок строк «ИМЯ = значение» -> словарь для layout.json."""
    import ast
    числа = {}
    for стр in блок.splitlines():
        стр = стр.split("#", 1)[0].strip()
        if not стр or "=" not in стр:
            continue
        имена, значение = (ч.strip() for ч in стр.split("=", 1))
        имена = [и.strip() for и in имена.split(",")]
        узел = ast.parse(значение, mode="eval").body
        if isinstance(узел, ast.Call):        # dict(w=1, h=2, ...)
            знач = {к.arg: ast.literal_eval(к.value) for к in узел.keywords}
        else:
            знач = ast.literal_eval(узел)
        if len(имена) > 1:
            числа.update(zip(имена, знач))
        else:
            числа[имена[0]] = знач
    # CAM_CROP_43 — подсказка для флага --camcrop, такого имени в config нет.
    числа.pop("CAM_CROP_43", None)
    return числа


