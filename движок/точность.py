# -*- coding: utf-8 -*-
"""
Точные границы слов по ЗВУКУ, а не по таймкоду распознавания.

Зачем. Распознавание ставит начало слова ПОЗЖЕ реальной атаки — замерено,
до 0.25 секунды. Режешь клип по его границе — первый слог срезан, и фраза
начинается невнятно. На слух это читается как «все начальные фразы будто
обрезаны». Симметрично на хвосте: последнее слово проглатывается.

Лечится просто: идти назад от слова, пока громкость не упадёт до фонового
уровня, и резать там.

Использование из кода:

    import точность
    точность.открыть("work/мой-стрим/audio16k.wav")
    s = точность.начало(125.480)     # реальная атака слова
    e = точность.конец(127.900)      # реальный хвост слова

Проверить из командной строки:

    python точность.py "work/мой-стрим/audio16k.wav" 125.480 127.900
"""
import sys
import wave
from pathlib import Path

import numpy as np

try:
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
except Exception:
    pass

ЧАСТОТА = 16000          # столько ставит extract_audio в clipper.py
_звук = None


def читать_wav(путь):
    """WAV 16 кГц моно в float32 от -1 до 1, штатным модулем wave."""
    with wave.open(str(путь), "rb") as w:
        кадров = w.getnframes()
        сырые = w.readframes(кадров)
        каналов = w.getnchannels()
    a = np.frombuffer(сырые, dtype=np.int16).astype(np.float32) / 32768.0
    if каналов > 1:
        a = a.reshape(-1, каналов).mean(axis=1)
    return a


def открыть(путь):
    """Загрузить дорожку. Обычно это движок/work/<стрим>/audio16k.wav."""
    global _звук
    путь = Path(путь)
    if not путь.exists():
        raise FileNotFoundError(
            "Нет файла %s. Сначала прогони: python clipper.py scan \"<стрим>\" — "
            "он извлекает аудио в кэш." % путь)
    _звук = читать_wav(путь)
    return len(_звук) / ЧАСТОТА


def _огибающая(t0, t1, шаг=0.005):
    if _звук is None:
        raise RuntimeError("Сначала точность.открыть(путь к audio16k.wav)")
    a = _звук[int(max(t0, 0) * ЧАСТОТА):int(max(t1, 0) * ЧАСТОТА)]
    окно = int(ЧАСТОТА * 0.020)
    прыжок = int(ЧАСТОТА * шаг)
    n = max(1, (len(a) - окно) // прыжок)
    return np.array([np.sqrt((a[i * прыжок:i * прыжок + окно] ** 2).mean() + 1e-12)
                     for i in range(n)]), шаг


def начало(слово_с, назад=0.45):
    """Реальная атака слова: идём назад, пока громкость выше фона."""
    t0 = max(0.0, слово_с - назад)
    e, шаг = _огибающая(t0, слово_с + 0.06)
    if len(e) < 5:
        return слово_с
    фон = np.percentile(e, 15)
    порог = max(фон * 2.2, e.max() * 0.10)
    i = len(e) - 1
    while i > 0 and e[i] > порог:
        i -= 1
    return round(t0 + i * шаг, 3)


def конец(слово_по, вперёд=0.35):
    """Не обрубить хвост слова: идём вперёд, пока громкость не упадёт."""
    e, шаг = _огибающая(max(0, слово_по - 0.06), слово_по + вперёд)
    if len(e) < 5:
        return слово_по
    фон = np.percentile(e, 15)
    порог = max(фон * 2.0, e.max() * 0.12)
    i = 0
    while i < len(e) - 1 and e[i] > порог:
        i += 1
    return round(слово_по - 0.06 + i * шаг, 3)


def границы(слово_с, слово_по):
    """Обе границы разом, с проверкой, что они не схлопнулись."""
    s, e = начало(слово_с), конец(слово_по)
    if e - s < 0.15:
        return слово_с, слово_по
    return s, e


if __name__ == "__main__":
    if len(sys.argv) < 4:
        print(__doc__)
        sys.exit(1)
    длина = открыть(sys.argv[1])
    a, b = float(sys.argv[2]), float(sys.argv[3])
    s, e = границы(a, b)
    print("  дорожка: %.1f сек" % длина)
    print("  распознавание: %.3f .. %.3f" % (a, b))
    print("  по звуку:      %.3f .. %.3f" % (s, e))
    print("  сдвиг входа:   %+.3f сек" % (s - a))
    print("  сдвиг хвоста:  %+.3f сек" % (e - b))
