"""
Поиск игровых моментов в записи стрима по связке сигналов.

    python игра.py "<стрим>"              таблица кандидатов
    python игра.py "<стрим>" --топ 20     сколько кандидатов показать
    python игра.py "<стрим>" --кадры      ещё и контактные листы кандидатов
    python игра.py "<стрим>" --заново     пересчитать кэш экранных сигналов

Сначала должны быть выполнены  clipper.py scan  и  clipper.py asr.

Сигналы:
  1. слова в расшифровке и кодовая фраза стримера;
  2. всплеск голоса относительно обычной громкости этого стримера;
  3. счёт убийств на экране (пока только Dota 2);
  5. движение в игровой части кадра.

Результат — кандидаты, а не готовые клипы: каждый проверяется по кадрам.
Порядок работы описан в .claude/знания/10-игровые-моменты.md.
"""
