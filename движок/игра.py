# Кодовая фраза стримера (регулярное выражение в CODE_PHRASE, мои_настройки.py):
# распознавание может поставить любую пунктуацию. None — фразы нет.
КОДОВАЯ_ФРАЗА = re.compile(clipper.C.CODE_PHRASE, re.I) if getattr(clipper.C, "CODE_PHRASE", None) else None

# Сколько секунд до кодовой фразы брать в кандидат. Итоговая длина ролика
# определяется после просмотра кадров этого окна.
ОКНО_ДО_ФРАЗЫ = 120

# Слова и их вес. Вес маленький у того, что стример говорит и без повода.
СЛОВА = [
    (re.compile(r"на клип|в клип|клипаем|клипок|маркер", re.I), 5.0),
    (re.compile(r"затащ|вынес|разъеб|рампаг|rampage|ultra ?kill|ультра ?килл|"
                r"триплет|тройн\w+ килл|четыре убийства", re.I), 2.0),
    (re.compile(r"ебать что|что (папа|я) сделал|вот это да|красиво|снял", re.I), 1.5),
    (re.compile(r"красав|легенд|респект|найс|\bnice\b|\bwp\b|well played|ой мужики", re.I), 0.7),
]

# Положение элементов интерфейса Dota 2 в долях кадра 16:9.
ПОЛОСА_X = (0.44, 0.56)            # полоса счёта вверху по центру
ПОЛОСА_Y = (0.0, 0.04)
СЧЁТ_ЛЕВО_X = (0.450, 0.478)
СЧЁТ_ПРАВО_X = (0.526, 0.554)
СЧЁТ_Y = (0.008, 0.030)
ТАЙМЕР_X = (0.490, 0.512)
ТАЙМЕР_Y = (0.021, 0.035)
ДВИЖЕНИЕ_X = (0.2, 0.8)            # игровая часть без вебки и панели героя
ДВИЖЕНИЕ_Y = (0.06, 0.72)

ПОРОГ_СЧЁТА = 8.0                  # средняя разница яркости при смене цифры
ПОРОГ_ТАЙМЕРА = 3.0                # таймер идёт: цифры меняются между кадрами
ПОРОГ_ТИШИНЫ = 4.0                 # цифры счёта стоят на месте
ОКНО = 25                          # длина окна поиска момента, секунды
МЕЖДУ = 40                         # минимальное расстояние между кандидатами
МИН_БАЛЛ = 3.0                     # ниже этого окно не считается кандидатом
МИН_ДЛИНА, МАКС_ДЛИНА = 12, 35     # допустимая длина предлагаемого куска


def кусок(кадр, доли_x, доли_y, ширина, высота):
    x0, x1 = int(доли_x[0] * ширина), int(доли_x[1] * ширина)
    y0, y1 = int(доли_y[0] * высота), int(доли_y[1] * высота)
    return кадр[y0:y1, x0:x1]


def размер_кадра(src):
    r = subprocess.run(["ffprobe", "-v", "error", "-select_streams", "v:0",
                        "-show_entries", "stream=width,height", "-of", "csv=p=0", str(src)],
                       capture_output=True, text=True, check=True)
    ш, в = r.stdout.strip().split(",")[:2]
    return int(ш), int(в)


def экранные_сигналы(src, кэш, заново=False):
    """Разница кадров по опорным кадрам видео: быстро и без полного декодирования."""
    файл = кэш / "игра_сигналы.npz"
    if файл.exists() and not заново:
        д = np.load(файл)
        return д["t"], д["лево"], д["право"], д["таймер"], д["движение"]

    W, H = размер_кадра(src)
    x0 = int(W * ПОЛОСА_X[0]) & ~1
    ш = int(W * (ПОЛОСА_X[1] - ПОЛОСА_X[0])) & ~1
    в_полосы = int(H * ПОЛОСА_Y[1]) & ~1
    в_мини = int(ш * H / W) & ~1
    граф = (f"[0:v]format=gray,split=2[a][b];[a]crop={ш}:{в_полосы}:{x0}:0[s];"
            f"[b]scale={ш}:{в_мини}[m];[s][m]vstack=inputs=2,showinfo[out]")
    cmd = ["ffmpeg", "-v", "info", "-nostats", "-skip_frame", "nokey", "-i", str(src),
           "-filter_complex", граф, "-map", "[out]", "-an", "-sn",
           "-fps_mode", "passthrough", "-f", "rawvideo", "-pix_fmt", "gray", "-"]

    размер = ш * (в_полосы + в_мини)
    лево, право, таймер, движение = [], [], [], []
    прошлый = None
    def сравнить(a, b, x, y, база_ш, база_в):
        return float(np.abs(кусок(a, x, y, база_ш, база_в).astype(np.int32) -
                            кусок(b, x, y, база_ш, база_в).astype(np.int32)).mean())

    def в_полосу(доли_x, доли_y):
        """Доли заданы от всего кадра: переводим их в доли полосы."""
        д_ш = ПОЛОСА_X[1] - ПОЛОСА_X[0]
        return (((доли_x[0] - ПОЛОСА_X[0]) / д_ш, (доли_x[1] - ПОЛОСА_X[0]) / д_ш),
                (доли_y[0] / ПОЛОСА_Y[1], доли_y[1] / ПОЛОСА_Y[1]))

    with tempfile.TemporaryFile() as лог:
        p = subprocess.Popen(cmd, stdout=subprocess.PIPE, stderr=лог)
        try:
            while True:
                буфер = p.stdout.read(размер)
                if len(буфер) < размер:
                    break
                кадр = np.frombuffer(буфер, dtype=np.uint8).reshape(в_полосы + в_мини, ш).astype(np.int16)
                полоса, мини = кадр[:в_полосы], кадр[в_полосы:]
                if прошлый is None:
                    d = (0.0, 0.0, 0.0, 0.0)
                else:
                    п_полоса, п_мини = прошлый
                    d = (сравнить(полоса, п_полоса, *в_полосу(СЧЁТ_ЛЕВО_X, СЧЁТ_Y), ш, в_полосы),
                         сравнить(полоса, п_полоса, *в_полосу(СЧЁТ_ПРАВО_X, СЧЁТ_Y), ш, в_полосы),
                         сравнить(полоса, п_полоса, *в_полосу(ТАЙМЕР_X, ТАЙМЕР_Y), ш, в_полосы),
                         сравнить(мини, п_мини, ДВИЖЕНИЕ_X, ДВИЖЕНИЕ_Y, ш, в_мини))
                лево.append(d[0]); право.append(d[1]); таймер.append(d[2]); движение.append(d[3])
                прошлый = (полоса, мини)
        except BaseException:
            p.kill()
            raise
        finally:
            p.stdout.close()
        код = p.wait()
        лог.seek(0)
        текст = лог.read().decode("utf-8", "replace")
    if код != 0:
        raise SystemExit("ffmpeg не смог прочитать видео:\n" + текст[-1500:])
    t = [float(x) for x in re.findall(r"pts_time:([\d.]+)", текст)]
    n = min(len(t), len(лево))
    if n == 0:
        raise SystemExit("Не удалось снять ни одного кадра.")
    массивы = [np.array(a[:n], dtype=np.float32) for a in (t, лево, право, таймер, движение)]
    np.savez(файл, t=массивы[0], лево=массивы[1], право=массивы[2],
             таймер=массивы[3], движение=массивы[4])
    return tuple(массивы)


def громкость_по_секундам(путь):
    """Громкость каждой секунды дорожки в дБ."""
    значения = []
    with wave.open(str(путь), "rb") as w:
        частота = w.getframerate()
        while True:
            сырые = w.readframes(частота)
            if len(сырые) < частота:        # меньше половины секунды 16-битного звука
                break
            a = np.frombuffer(сырые, dtype=np.int16).astype(np.float32) / 32768.0
            значения.append(10 * np.log10(float((a ** 2).mean()) + 1e-10))
    return np.array(значения, dtype=np.float32)


def всплеск_голоса(дб):
    """Превышение над обычной громкостью стримера: опора считается по минутам."""
    минут = max(1, len(дб) // 60)
    опора = []
    for м in range(минут):
        кусок_дб = дб[max(0, (м - 2) * 60):(м + 3) * 60]
        речь = кусок_дб[кусок_дб > -50]
        опора.append(float(np.median(речь)) if len(речь) else -40.0)
    центры = np.arange(минут) * 60 + 30
    база = np.interp(np.arange(len(дб)), центры, опора)
    return np.clip((дб - база) / 6.0, 0, 3)


def слова_по_секундам(реплики, длина):
    """Вес слов по секундам и список моментов с кодовой фразой."""
    вес = np.zeros(длина, dtype=np.float32)
    кодовые = []
    for i, р in enumerate(реплики):
        текст = р["text"]
        нач, кон = float(р["start"]), float(р["end"])

        # Длинные реплики склеены: позицию слова оцениваем по месту в тексте.
        def секунда(позиция):
            return int(нач + (кон - нач) * min(позиция, len(текст)) / max(1, len(текст)))

        # Распознавание может разрезать фразу на границе реплик.
        следующая = реплики[i + 1]["text"] if i + 1 < len(реплики) else ""
        for м in (КОДОВАЯ_ФРАЗА.finditer(текст + " " + следующая) if КОДОВАЯ_ФРАЗА else ()):
            if м.start() < len(текст):
                кодовые.append(секунда(м.start()))
        for шаблон, значение in СЛОВА:
            for м in шаблон.finditer(текст):
                с = секунда(м.start())
                if 0 <= с < длина:
                    вес[с] += значение
    return вес, кодовые


def в_секунды(t, значения, длина):
    """Максимум значения за каждую секунду; пропуски заполняются нулём."""
    итог = np.zeros(длина, dtype=np.float32)
    индексы = np.clip(t.astype(np.int64), 0, длина - 1)
    np.maximum.at(итог, индексы, значения)
    return итог


def чч_мм_сс(с):
    с = int(с)
    return "%d:%02d:%02d" % (с // 3600, с % 3600 // 60, с % 60)


def найти_кандидатов(t, лево, право, таймер, движение, голос, слова, кодовые, реплики, топ):
    длина = len(голос)
    if длина == 0:
        return []
    # Таймер матча идёт только в самой игре: так отсекаются меню и разговорная сцена.
    # В подвижных меню цифры счёта тоже «меняются», поэтому они должны быть спокойны.
    тихо = (лево < ПОРОГ_ТИШИНЫ) & (право < ПОРОГ_ТИШИНЫ)
    # Срез вместо mode="same": на коротком видео тот вернул бы массив другой длины.
    идёт = np.convolve(((таймер > ПОРОГ_ТАЙМЕРА) & тихо).astype(np.float32),
                       np.ones(9) / 9, mode="full")[4:4 + len(таймер)] > 0.6
    шаг_счёта = ((лево > ПОРОГ_СЧЁТА) | (право > ПОРОГ_СЧЁТА)) & идёт
    убийства = в_секунды(t, шаг_счёта.astype(np.float32), длина)
    # Кадры идут реже секунды: непрерывные сигналы растягиваем на все секунды.
    секунды = np.arange(длина)
    в_игре = np.interp(секунды, t, идёт.astype(np.float32))
    порог_дв = np.percentile(движение[идёт], [50, 95]) if идёт.any() else (1.0, 2.0)
    дв = np.clip((движение - порог_дв[0]) / max(порог_дв[1] - порог_дв[0], 0.1), 0, 1)
    дв_сек = np.interp(секунды, t, дв)
    сумма_у, сумма_с = np.cumsum(убийства), np.cumsum(слова)

    очки, поля = np.zeros(длина, dtype=np.float32), {}
    for с in range(0, длина - ОКНО + 1):
        к = min(с + ОКНО, длина - 1)
        у = float(сумма_у[к] - сумма_у[с])
        сл = float(сумма_с[min(к + 5, длина - 1)] - сумма_с[с])
        г = float(голос[с:к].max())
        д = float(np.percentile(дв_сек[с:к], 75))
        доля = float(в_игре[с:к].mean())
        балл = 3.0 * min(у, 5) + 2.0 * min(сл, 5) + 1.5 * г + 2.0 * д
        # Вне матча остаются только явные словесные метки.
        очки[с] = балл if доля >= 0.7 else 0.2 * балл
        поля[с] = (у, сл, г, д)

    найденные = []
    занято = np.zeros(длина, dtype=bool)

    def текст_вокруг(a, b):
        куски = [р["text"].strip() for р in реплики if р["end"] >= a and р["start"] <= b]
        return " ".join(куски)[:160]

    # Кодовая фраза всегда идёт первой: стример сам пометил момент.
    предыдущая_фраза = 0
    for к in sorted(set(кодовые)):
        if занято[min(к, длина - 1)]:       # повтор фразы рядом с предыдущей
            continue
        # Окно не заходит за предыдущую фразу, чтобы кандидаты не пересекались.
        a = max(0, к - ОКНО_ДО_ФРАЗЫ, предыдущая_фраза)
        найденные.append(dict(начало=a, конец=к, балл=100.0, метка="кодовая фраза",
                              убийств=int(убийства[a:к + 1].sum()), текст=текст_вокруг(a, к)))
        занято[a:min(длина, к + МЕЖДУ)] = True
        предыдущая_фраза = к

    порядок = np.argsort(-очки)
    for с in порядок:
        if len(найденные) >= топ or очки[с] < МИН_БАЛЛ:
            break
        с = int(с)
        if занято[с:с + ОКНО].any():
            continue
        у, сл, г, д = поля[с]
        шаги = np.nonzero(убийства[с:с + ОКНО])[0]
        if len(шаги):
            a, b = с + int(шаги[0]) - 8, с + int(шаги[-1]) + 6
        else:
            a, b = с, с + ОКНО
        if b - a < МИН_ДЛИНА:
            b = a + МИН_ДЛИНА
        b = min(b, a + МАКС_ДЛИНА, длина - 1)
        a = max(0, a)
        найденные.append(dict(начало=int(a), конец=int(b), балл=round(float(очки[с]), 1),
                              метка="сигналы", убийств=int(у), слова=round(сл, 1),
                              голос=round(г, 1), движение=round(д, 2),
                              текст=текст_вокруг(a, b)))
        занято[max(0, с - МЕЖДУ):min(длина, с + МЕЖДУ)] = True
    return найденные


def контактные_листы(src, кэш, кандидаты):
    папка = кэш / "игра_кадры"
    папка.mkdir(exist_ok=True)
    for i, к in enumerate(кандидаты, 1):
        d = max(1, к["конец"] - к["начало"])
        имя = папка / ("%02d_%s.jpg" % (i, чч_мм_сс(к["начало"]).replace(":", "-")))
        subprocess.run(["ffmpeg", "-y", "-v", "error", "-ss", str(к["начало"]), "-t", str(d),
                        "-i", str(src), "-vf", f"fps={6 / d:.4f},scale=520:-1,tile=3x2",
                        "-frames:v", "1", str(имя)], check=True)
        к["кадры"] = str(имя)
    print("  контактные листы: %s" % папка)


def главное():
    арг = sys.argv[1:]
    if not арг or арг[0].startswith("--"):
        print(__doc__)
        return 1
    src = Path(арг[0])
    if not src.exists():
        print("  Файла нет: %s" % src)
        return 1
    топ = 15
    if "--топ" in арг:
        try:
            топ = int(арг[арг.index("--топ") + 1])
        except (IndexError, ValueError):
            print("  После --топ нужно число, например --топ 20")
            return 1

    кэш = clipper.stream_cache(src)
    звук, расшифровка = кэш / "audio16k.wav", кэш / "transcript.json"
    if not звук.exists() or not расшифровка.exists():
        print("  Сначала выполни clipper.py scan и clipper.py asr для этого файла.")
        return 1

    print("  снимаю сигналы экрана...")
    t, лево, право, таймер, движение = экранные_сигналы(src, кэш, "--заново" in арг)
    print("  считаю голос и слова...")
    дб = громкость_по_секундам(звук)
    голос = всплеск_голоса(дб)
    реплики = json.loads(расшифровка.read_text(encoding="utf-8"))
    слова, кодовые = слова_по_секундам(реплики, len(голос))

    кандидаты = найти_кандидатов(t, лево, право, таймер, движение, голос, слова,
                                 кодовые, реплики, топ)
    if "--кадры" in арг:
        контактные_листы(src, кэш, кандидаты)
    выход = кэш / "game_candidates.json"
    выход.write_text(json.dumps(кандидаты, ensure_ascii=False, indent=1), encoding="utf-8")

    print("")
    print("  кодовых фраз: %d, кандидатов: %d -> %s" % (len(кодовые), len(кандидаты), выход))
    for к in кандидаты:
        print("  %-8s %3d сек  балл %5.1f  убийств %d  %s" % (
            чч_мм_сс(к["начало"]), к["конец"] - к["начало"], к["балл"], к["убийств"], к["текст"][:90]))
    return 0


if __name__ == "__main__":
    sys.exit(главное())
