# -*- coding: utf-8 -*-
"""
Завершение партии после того, как пользователь принял все ролики.

    python приёмка.py "<папка «Мем …» в Clips Ready>"  "<файл записи в СТРИМЫ>"
    python приёмка.py "<папка «Матч …» в Clips Ready>" "<файл в СЫРЫЕ МАТЧИ>"
    python приёмка.py "<папка «Файт …» в Clips Ready>" --сырые "<файл>" "<файл>" ...

Собирает ролики папки в архив (если их больше одного), проверяет его и только затем удаляет
исходники: запись стрима, запись матча или перечисленные файлы из СЫРЫЕ КЛИПЫ.
Тип папки должен совпасть с папкой исходника.
Запускать только после явного «принято» от пользователя.
"""
import argparse
import os
import re
import sys
import zipfile
from pathlib import Path

sys.dont_write_bytecode = True     # чтобы не плодить папки __pycache__

import пути  # первым: переносит кэши и временные файлы в .cache проекта
пути.требовать_окружение()

for _поток in (sys.stdout, sys.stderr):
    try:
        _поток.reconfigure(encoding="utf-8", errors="replace")
    except Exception:
        pass

КОРЕНЬ = Path(__file__).resolve().parent.parent
ГОТОВЫЕ = КОРЕНЬ / "Clips Ready"
ЗАПИСИ = КОРЕНЬ / "СТРИМЫ"
СЫРЫЕ = КОРЕНЬ / "СЫРЫЕ КЛИПЫ"
МАТЧИ = КОРЕНЬ / "СЫРЫЕ МАТЧИ"
ВИДЕО = {".mp4", ".mkv", ".ts", ".flv", ".webm", ".mov"}


def найти_ролики(папка):
    """Ролики партии. Версии без текста из старых партий в архив не входят."""
    ролики = sorted(п for п in папка.rglob("*.mp4") if "(без текста)" not in п.name)
    if not ролики:
        raise SystemExit("В папке нет роликов, исходники не тронуты")
    # Windows не различает регистр имён, поэтому сравнение идёт без него.
    имена = [п.name.lower() for п in ролики]
    if len(set(имена)) != len(имена):
        raise SystemExit("В партии есть ролики с одинаковыми именами, исходники не тронуты")
    пустые = [п.name for п in ролики if п.stat().st_size == 0]
    if пустые:
        raise SystemExit(f"Есть пустые ролики, исходники не тронуты: {', '.join(пустые)}")
    return ролики


def собрать_архив(папка, ролики):
    """Пишет архив во временный файл и переименовывает его только после проверки."""
    архив = папка / f"Архив {папка.name}.zip"
    черновик = архив.with_name(архив.name + ".part")
    try:
        # Видео уже сжато, поэтому файлы кладутся без повторного сжатия.
        with zipfile.ZipFile(черновик, "w", zipfile.ZIP_STORED, allowZip64=True) as z:
            for ролик in ролики:
                z.write(ролик, arcname=ролик.name)
        with zipfile.ZipFile(черновик) as z:
            размеры_совпали = all(z.getinfo(р.name).file_size == р.stat().st_size
                                  for р in ролики)
            if z.testzip() is not None or not размеры_совпали:
                raise SystemExit("Архив собрался с ошибкой, исходники не тронуты")
        os.replace(черновик, архив)
    finally:
        # После успешного переименования черновика уже нет.
        черновик.unlink(missing_ok=True)
    return архив


def упаковать(папка, ролики):
    """
    Архив нужен, только когда роликов несколько: их удобно отправить одним
    файлом. Один ролик архив не уменьшает (видео уже сжато), поэтому его
    не пакуем (решение пользователя 2026-11-20).
    """
    if len(ролики) == 1:
        print(f"Ролик один, архив не нужен: {ролики[0].name}")
        return
    архив = собрать_архив(папка, ролики)
    print(f"Архив: {архив} ({len(ролики)} роликов)")


def удалить(файл):
    """Удаляет файл и сообщает итог. На Windows файл может быть занят плеером."""
    try:
        файл.unlink()
    except OSError as ошибка:
        print(f"Не удалось удалить: {файл.name} ({ошибка.strerror})")
        return False
    print(f"Удалён: {файл.name}")
    return True


# Тип партии в начале имени папки (с 2026-11-20): «Мем …», «Файт …», «Матч …».
# Старые папки без типа принимаются как раньше.
ДАТА = r"\d{4}-\d{2}-\d{2} \d{2}-\d{2}"
ДЛИНА = r"( (\d+ч )?\d+м)?"


def принять_сырые(папка, пути_файлов):
    """Архивирует партию из сырых клипов и удаляет только перечисленные файлы."""
    # Имя папки партии: «Файт <дата> <время>[ <название>]» или старое
    # «<дата> <время>[ сырые клипы <имя>]».
    if not (re.fullmatch(rf"Файт {ДАТА}( .+)?", папка.name)
            or re.fullmatch(rf"{ДАТА}( сырые клипы .+)?", папка.name)):
        raise SystemExit("Это не папка партии из сырых клипов (нужна «Файт …»), "
                         "ничего не сделано")
    # dict.fromkeys убирает повторы и сохраняет порядок файлов.
    файлы = list(dict.fromkeys(Path(п).resolve() for п in пути_файлов))
    сырые = СЫРЫЕ.resolve()
    # Всё проверяется до архива, чтобы ошибка в одном имени ничего не затронула.
    for файл in файлы:
        # Файл может лежать и во вложенной папке СЫРЫЕ КЛИПЫ
        # (например, «смотреть последние 50 секунд»), но не за её пределами.
        if сырые not in файл.parents or файл.suffix.lower() not in ВИДЕО:
            raise SystemExit(f"Файл должен быть видео внутри СЫРЫЕ КЛИПЫ, "
                             f"ничего не сделано: {файл.name}")
        if not файл.is_file():
            raise SystemExit(f"Файл не найден, ничего не сделано: {файл.name}")

    ролики = найти_ролики(папка)
    упаковать(папка, ролики)
    # Ошибка на одном файле не останавливает удаление остальных.
    результаты = [удалить(файл) for файл in файлы]
    if not all(результаты):
        raise SystemExit("Приёмка выполнена, но удалены не все файлы: закройте их и удалите вручную")


def принять_запись(папка, запись):
    """
    Партия из одной записи: мемы из стрима (СТРИМЫ) или матч (СЫРЫЕ МАТЧИ).
    Тип в имени папки обязан совпасть с папкой исходника, иначе ничего
    не удаляется: так приёмка мемов не сотрёт чужой матч и наоборот.
    """
    запись = Path(запись).resolve()
    if запись.suffix.lower() not in ВИДЕО:
        raise SystemExit("Запись должна быть видеофайлом, ничего не сделано")
    откуда = {ЗАПИСИ.resolve(): "Мем", МАТЧИ.resolve(): "Матч"}.get(запись.parent)
    if откуда is None:
        raise SystemExit("Запись должна лежать прямо в СТРИМЫ или СЫРЫЕ МАТЧИ, "
                         "ничего не сделано")
    if not запись.is_file():
        raise SystemExit("Файл записи не найден, ничего не сделано")
    имя = re.escape(запись.stem)
    типовая = re.fullmatch(rf"(Мем|Файт|Матч) {ДАТА} {имя}{ДЛИНА}", папка.name)
    старая = re.fullmatch(rf"{ДАТА} {имя}{ДЛИНА}", папка.name)
    if типовая:
        if типовая.group(1) != откуда:
            raise SystemExit(f"Папка «{типовая.group(1)} …», а запись из папки для "
                             f"«{откуда}»: не та пара, ничего не сделано")
    elif not (старая and откуда == "Мем"):
        raise SystemExit("Запись не относится к этой папке роликов, ничего не сделано")

    ролики = найти_ролики(папка)
    упаковать(папка, ролики)
    if not удалить(запись):
        raise SystemExit("Приёмка выполнена, но запись не удалена: закройте её и удалите вручную")


def main():
    разбор = argparse.ArgumentParser(description=__doc__)
    разбор.add_argument("папка", help="папка партии внутри Clips Ready")
    разбор.add_argument("запись", nargs="?",
                        help="файл записи внутри СТРИМЫ (мемы) или СЫРЫЕ МАТЧИ (матч)")
    разбор.add_argument("--сырые", nargs="+", metavar="ФАЙЛ",
                        help="файлы внутри СЫРЫЕ КЛИПЫ, из которых собрана партия")
    арг = разбор.parse_args()

    папка = Path(арг.папка).resolve()
    if папка.parent != ГОТОВЫЕ.resolve() or not папка.is_dir():
        raise SystemExit("Папка роликов должна лежать прямо в Clips Ready, ничего не сделано")
    # Нужен ровно один вид исходников: либо запись, либо сырые клипы.
    if bool(арг.запись) == bool(арг.сырые):
        raise SystemExit("Нужно указать либо запись, либо --сырые, ничего не сделано")
    if арг.сырые:
        принять_сырые(папка, арг.сырые)
    else:
        принять_запись(папка, арг.запись)


if __name__ == "__main__":
    main()
